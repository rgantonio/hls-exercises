#!/usr/bin/env bash
# bench/tools/get_bambu.sh: install Bambu (PandA) 2024.10 into tools/ (BAM1).
# Downloads the release AppImage, checks its sha256 against the pin below, extracts it
# with --appimage-extract (no FUSE needed) into tools/bambu/squashfs-root/, and writes
# the wrapper tools/bin/bambu. Run from anywhere: `pixi run get-bambu`.
# The 2024.10 GitHub release (github.com/ferrandi/PandA-bambu/releases/tag/2024.10) has
# no assets; its notes link to the AppImage below.
set -euo pipefail

VERSION=2024.10
URL="https://release.bambuhls.eu/bambu-${VERSION}.AppImage"
SHA256="e4f0214496a5d35de1932975b0f41cd95bc33a53a904fc565d6c2cb01df40773"  # pinned from the first download, 2026-11-03

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DEST="$ROOT/tools/bambu"
IMG="$DEST/bambu-${VERSION}.AppImage"
mkdir -p "$DEST" "$ROOT/tools/bin"

if [ ! -f "$IMG" ]; then
    echo "downloading $URL"
    curl -fL --retry 3 -o "$IMG.part" "$URL"
    mv "$IMG.part" "$IMG"
fi

got="$(sha256sum "$IMG" | cut -d' ' -f1)"
if [ -z "$SHA256" ]; then
    echo "no sha256 pinned; this download is $got (pin it in $0)" >&2
    exit 1
fi
if [ "$got" != "$SHA256" ]; then
    echo "sha256 mismatch for $IMG: got $got, pinned $SHA256" >&2
    exit 1
fi
echo "sha256 ok: $got"

if [ ! -x "$DEST/squashfs-root/AppRun" ]; then
    rm -rf "$DEST/squashfs-root"
    chmod +x "$IMG"
    (cd "$DEST" && "$IMG" --appimage-extract > /dev/null)
fi

cat > "$ROOT/tools/bin/bambu" <<WRAP
#!/usr/bin/env bash
# Generated by bench/tools/get_bambu.sh: Bambu ${VERSION} from the extracted AppImage.
# The AppImage runtime normally sets APPDIR, ARGV0 and OWD; the extracted AppRun
# (usr/bin/tool_select.sh) needs them to find usr/bin/bambu and the caller's directory.
export APPDIR="$DEST/squashfs-root"
export ARGV0=bambu
export OWD="\$PWD"
exec "$DEST/squashfs-root/AppRun" "\$@"
WRAP
chmod +x "$ROOT/tools/bin/bambu"
echo "wrote $ROOT/tools/bin/bambu"
