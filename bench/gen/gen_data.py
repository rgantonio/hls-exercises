#!/usr/bin/env python3
"""bench/gen/gen_data.py - test vectors from snax-forge's own kernel files.

Runs in snax-forge's pixi environment (it imports the kernel files, which
import snax_forge and dace), so the inputs and expected outputs are the ones
forge uses:

  pixi run --manifest-path $FORGE/pixi.toml \\
      python $PWD/bench/gen/gen_data.py --forge $FORGE [--tier done] [--kernel vecadd]

For every kernel folder bench/tier_*/<kernel>/ with a params.json, and every
size in it, this writes vectors/<size>/data.h:

  IN_<arg>    the value every argument starts with (outputs too)
  EXP_<arg>   the expected value of every inout argument

The arrays keep the kernel's shapes (A[38][42] stays 2-D). data_t is the
testbench's typedef; the header has no includes of its own.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
BENCH = ROOT / "bench"


def load_spec(forge: Path, rel: str):
    """rel is the kernel file under forge's kernels/, e.g. polybench/vecadd."""
    path = forge / "kernels" / f"{rel}.py"
    if not path.is_file():
        sys.exit(f"no kernel file {path}")
    sys.path.insert(0, str(forge))
    spec = importlib.util.spec_from_file_location(f"forge_kernel_{path.stem}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.SPEC


def c_array(name: str, arr: np.ndarray) -> str:
    dims = "".join(f"[{d}]" for d in arr.shape) or "[1]"
    flat = arr.reshape(-1) if arr.ndim else arr.reshape(1)

    def nest(a: np.ndarray, indent: str) -> str:
        if a.ndim <= 1:
            vals = [str(int(v)) if np.issubdtype(a.dtype, np.integer) else repr(float(v)) for v in a.reshape(-1)]
            rows = [", ".join(vals[i:i + 16]) for i in range(0, len(vals), 16)]
            return "{\n" + ",\n".join(indent + "  " + r for r in rows) + "\n" + indent + "}"
        return "{\n" + ",\n".join(indent + "  " + nest(x, indent + "  ") for x in a) + "\n" + indent + "}"

    body = nest(arr if arr.ndim else flat, "")
    return f"static const data_t {name}{dims} = {body};\n"


def write_data(kdir: Path, params: dict, forge: Path) -> None:
    spec = load_spec(forge, params["forge_kernel"])
    seed = int(params.get("seed", 0))
    for size in params["sizes"]:
        tag = "_".join(f"{k.lower()}{v}" for k, v in size.items())
        rng = np.random.default_rng(seed)
        inputs = spec.make_inputs(rng, **size)
        work = {k: np.array(v, copy=True) for k, v in inputs.items()}
        spec.reference(**work)

        out = [
            "// Generated by bench/gen/gen_data.py. Do not edit.",
            f"// snax-forge kernels/{params['forge_kernel']}.py, make_inputs(seed={seed}, {size})",
            "#pragma once",
            "",
        ]
        for name, arr in inputs.items():
            out.append(c_array(f"IN_{name}", np.asarray(arr)))
        for name in spec.inout:
            out.append(c_array(f"EXP_{name}", np.asarray(work[name])))
        dst = kdir / "vectors" / tag / "data.h"
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text("\n".join(out))
        print(f"wrote {dst.relative_to(ROOT)}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--forge", type=Path, required=True, help="snax-forge checkout")
    ap.add_argument("--tier")
    ap.add_argument("--kernel")
    args = ap.parse_args()
    n = 0
    for p in sorted(BENCH.glob("tier_*/*/params.json")):
        params = json.loads(p.read_text())
        tier = params.get("tier", p.parent.parent.name.removeprefix("tier_"))
        if (args.tier and tier != args.tier) or (args.kernel and params.get("kernel", p.parent.name) != args.kernel):
            continue
        write_data(p.parent, params, args.forge.resolve())
        n += 1
    if not n:
        sys.exit("no kernel folder matched")
    return 0


if __name__ == "__main__":
    sys.exit(main())
